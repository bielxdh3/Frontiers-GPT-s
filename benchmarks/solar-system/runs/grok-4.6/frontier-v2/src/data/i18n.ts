export type MsgKey = keyof typeof M

export function t(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s: string = M[key][lang]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

export function kindLabel(lang: Lang, kind: string): string {
  const map: Record<string, MsgKey> = {
    star: 'star',
    planet: 'planet',
    moon: 'moon',
    'dwarf-planet': 'dwarf',
    asteroid: 'asteroid',
    comet: 'comet',
    region: 'region',
  }
  return t(lang, map[kind] ?? 'planet')
}
